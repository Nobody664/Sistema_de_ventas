import "reflect-metadata";
import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { BadRequestException, NotFoundException } from "@nestjs/common";
import { Prisma } from "@prisma/client";
import { PrismaService } from "@/database/prisma/prisma.service";
import { AuditService } from "@/common/services/audit.service";
import { StockEntriesService } from "@/modules/stock-entries/stock-entries.service";
import { SuppliersService } from "./suppliers.service";
import { supplierOrderLines } from "./supplier-order.helper";
import type { CreateSupplierOrderDto } from "./dto/supplier.dto";

function fixture(
  options: { supplier?: boolean; products?: boolean; failAudit?: boolean } = {},
) {
  const state = { writes: 0, audits: 0, transactions: 0 };
  const tx = {
    supplier: {
      findFirst: async (args: Prisma.SupplierFindFirstArgs) => {
        assert.deepEqual(args.where, {
          id: "supplier-1",
          companyId: "company-a",
          deletedAt: null,
          isActive: true,
        });
        return options.supplier === false ? null : { id: "supplier-1" };
      },
    },
    product: {
      findMany: async (args: Prisma.ProductFindManyArgs) => {
        assert.equal(args.where?.companyId, "company-a");
        assert.equal(args.where?.isActive, true);
        assert.equal(args.where?.deletedAt, null);
        return options.products === false ? [] : [{ id: "p1" }, { id: "p2" }];
      },
    },
    supplierOrder: {
      create: async ({
        data,
      }: {
        data: {
          status: string;
          isAutoGenerated: boolean;
          totalEstimated: Prisma.Decimal | null;
          items: { create: ReturnType<typeof supplierOrderLines>["items"] };
        };
      }) => {
        state.writes++;
        assert.equal(data.status, "DRAFT");
        return { ...data, id: "order-1", items: data.items.create };
      },
    },
  };
  const prisma = {
    $transaction: async <T>(work: (client: typeof tx) => Promise<T>) => {
      state.transactions++;
      const before = { ...state };
      try {
        return await work(tx);
      } catch (error) {
        Object.assign(state, before);
        throw error;
      }
    },
  };
  const audit = {
    log: async (_input: unknown, client: unknown) => {
      assert.equal(client, tx);
      if (options.failAudit) throw new Error("audit failed");
      state.audits++;
    },
  };
  const stock = {
    createWithinTransaction: async () => {
      throw new Error("Creating a draft must not change stock");
    },
  };
  const service = new SuppliersService(
    prisma as unknown as PrismaService,
    audit as unknown as AuditService,
    stock as unknown as StockEntriesService,
  );
  const input: CreateSupplierOrderDto = {
    supplierId: "supplier-1",
    items: [
      { productId: "p1", requestedQuantity: 1.25, unitCost: 0.1001 },
      { productId: "p2", requestedQuantity: 2, unitCost: 3.5 },
    ],
  };
  return { service, state, input };
}

describe("Supplier purchase order creation", () => {
  it("splits automatic replenishment into receivable orders and carries quoted unit costs", async () => {
    const { service } = fixture();
    service.getAutoOrdersPreview = async () => ({
      groups: [
        {
          supplier: { id: "supplier-1", name: "Proveedor", code: null },
          estimatedTotal: 390,
          items: Array.from({ length: 130 }, (_, index) => ({
            productId: `p${index}`,
            productName: `P${index}`,
            sku: null,
            baseUnit: "UNIT",
            currentStock: 0,
            minStock: 1,
            missingUnits: 1,
            suggestedQuantity: 2,
            estimatedCost: 3,
          })),
        },
      ],
      unassigned: [],
    });
    const batches: CreateSupplierOrderDto[] = [];
    service.createOrder = async (companyId, userId, input, auto) => {
      assert.equal(companyId, "company-a");
      assert.equal(userId, "owner");
      assert.equal(auto, true);
      batches.push(input);
      return { id: `order-${batches.length}` } as unknown as Awaited<
        ReturnType<SuppliersService["createOrder"]>
      >;
    };
    const created = await service.generateAutoOrders("company-a", "owner");
    assert.equal(created.length, 2);
    assert.equal(batches[0].items.length, 100);
    assert.equal(batches[1].items.length, 30);
    assert.equal(batches[0].items[0].unitCost, 1.5);
  });
  it("creates an audited draft with exact decimal quantities and costs without changing inventory", async () => {
    const { service, state, input } = fixture();
    const order = await service.createOrder("company-a", "owner", input);
    assert.equal(order.totalEstimated, 7.1251);
    assert.equal(order.items[0].requestedQuantity, 1.25);
    assert.equal(order.items[0].unitCost, 0.1001);
    assert.equal(state.writes, 1);
    assert.equal(state.audits, 1);
  });
  it("does not represent an unknown quoted cost as a free purchase", async () => {
    const { service, input } = fixture();
    delete input.items[0].unitCost;
    const order = await service.createOrder("company-a", "owner", input);
    assert.equal(order.totalEstimated, null);
    assert.equal(order.items[0].unitCost, null);
  });
  it("rejects duplicate lines before starting a write transaction", async () => {
    const { service, state, input } = fixture();
    input.items[1].productId = "p1";
    await assert.rejects(
      service.createOrder("company-a", "owner", input),
      BadRequestException,
    );
    assert.equal(state.transactions, 0);
    assert.equal(state.writes, 0);
  });
  it("rejects inactive or foreign suppliers and products", async () => {
    for (const options of [{ supplier: false }, { products: false }]) {
      const { service, state, input } = fixture(options);
      await assert.rejects(
        service.createOrder("company-a", "owner", input),
        NotFoundException,
      );
      assert.equal(state.writes, 0);
    }
  });
  it("rolls back the order if its audit cannot be recorded", async () => {
    const { service, state, input } = fixture({ failAudit: true });
    await assert.rejects(
      service.createOrder("company-a", "owner", input),
      /audit failed/,
    );
    assert.equal(state.writes, 0);
    assert.equal(state.audits, 0);
  });
  it("rejects unreceivable precision, values and oversized orders", () => {
    for (const item of [
      { productId: "p1", requestedQuantity: 0 },
      { productId: "p1", requestedQuantity: 1.0001 },
      { productId: "p1", requestedQuantity: 1, unitCost: NaN },
      { productId: "p1", requestedQuantity: 1, unitCost: 0.00001 },
      { productId: "p1", requestedQuantity: 1, unitCost: -1 },
    ])
      assert.throws(() => supplierOrderLines([item]), BadRequestException);
    assert.throws(
      () =>
        supplierOrderLines(
          Array.from({ length: 101 }, (_, index) => ({
            productId: `p${index}`,
            requestedQuantity: 1,
          })),
        ),
      BadRequestException,
    );
    assert.throws(
      () =>
        supplierOrderLines([
          {
            productId: "p1",
            requestedQuantity: 99999999999,
            unitCost: 99999999,
          },
        ]),
      BadRequestException,
    );
  });
});
