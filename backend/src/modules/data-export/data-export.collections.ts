export function getExportDefinition(
  name: string,
): ExportCollection | undefined {
  if (!Object.hasOwn(exportCollections, name)) return undefined;
  return exportCollections[name as keyof typeof exportCollections];
}

export function validateExportDefinitions(): void {
  for (const definition of Object.values(exportCollections)) {
    const model = Prisma.dmmf.datamodel.models.find(
      (item) => item.name === definition.model,
    );
    if (
      !model ||
      definition.fields.some(
        (field) =>
          !model.fields.some(
            (item) => item.name === field && item.kind !== "object",
          ),
      )
    ) {
      throw new Error(`INVALID_EXPORT_DEFINITION:${definition.model}`);
    }
  }
}
