import Link from "next/link";
import { notFound } from "next/navigation";
import { ArrowLeft, ClipboardList } from "lucide-react";
import { Card } from "@/components/ui/card";
import { serverApiFetch } from "@/lib/server-api";
import { getServerSession } from "@/lib/session";
import { OrderStatusBadge } from "@/components/suppliers/order-status-badge";
import { OrderActions } from "@/components/suppliers/order-actions";
import type { SupplierOrder } from "@/types/suppliers";

export default async function PurchaseOrderDetailPage({
  params,
}: {
  params: Promise<{ id: string }>;
}) {
  const { id } = await params;
  const session = await getServerSession();
  const accessToken = session?.accessToken;

  const order = await serverApiFetch<SupplierOrder>(
    `/suppliers/orders/${id}`,
    accessToken,
  );

  if (!order) {
    notFound();
  }

  return (
    <div className="space-y-6">
      <Link
        href="/purchase-orders"
        className="flex items-center gap-2 text-sm text-foreground/50 transition-colors hover:text-foreground"
      >
        <ArrowLeft className="h-4 w-4" />
        Volver a órdenes de compra
      </Link>

      <Card className="rounded-[34px] bg-gradient-to-br from-slate-700 to-slate-900 p-6 sm:p-8 text-white animate-fade-in-up">
        <div className="flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between">
          <div className="flex items-center gap-4">
            <div className="rounded-2xl bg-white/20 p-3">
              <ClipboardList className="size-6" />
            </div>
            <div>
              <h1 className="font-display text-3xl">
                Orden de {order.supplier?.name ?? "proveedor"}
              </h1>
              <p className="mt-1 text-sm text-white/70">
                {order.isAutoGenerated
                  ? "Generada automáticamente"
                  : (order.reference ?? "Manual")}
              </p>
            </div>
          </div>
          <OrderStatusBadge status={order.status} />
        </div>
      </Card>

      <div className="grid gap-6 lg:grid-cols-[2fr_1fr]">
        <Card className="rounded-[30px] bg-white/85 p-6">
          <p className="mb-4 font-display text-lg">Productos</p>
          <div className="divide-y divide-foreground/10">
            {order.items.map((item) => (
              <div
                key={item.id}
                className="flex items-center justify-between gap-4 py-3 text-sm"
              >
                <div className="min-w-0">
                  <p className="truncate font-medium">
                    {item.product?.name ?? item.productId}
                  </p>
                  <p className="mt-1 break-all font-mono text-xs text-white/60">
                    ID: {order.id}
                  </p>
                  <p className="text-xs text-foreground/50">
                    {item.product?.sku ?? "Sin SKU"} ·{" "}
                    {item.product?.baseUnit ?? ""}
                  </p>
                </div>
                <div className="shrink-0 text-right">
                  <p className="font-medium">
                    Solicitado: {item.requestedQuantity}{" "}
                    {item.product?.baseUnit}
                  </p>
                  {order.receivedAt && (
                    <p className="mt-1 text-xs text-emerald-600">
                      Recibido: {item.receivedQuantity} {item.product?.baseUnit}
                    </p>
                  )}
                  {item.unitCost !== null && (
                    <p className="text-xs text-foreground/50">
                      S/ {(item.unitCost * item.requestedQuantity).toFixed(2)}
                    </p>
                  )}
                </div>
              </div>
            ))}
          </div>
          {order.totalEstimated !== null && (
            <div className="mt-4 flex items-center justify-between border-t border-foreground/10 pt-4">
              <span className="text-sm text-foreground/50">Total estimado</span>
              <span className="font-display text-xl">
                S/ {order.totalEstimated.toFixed(2)}
              </span>
            </div>
          )}
          {order.receivedAt && order.stockEntryId && (
            <div className="mt-4 flex items-center justify-between border-t pt-4">
              <span className="text-sm text-muted-foreground">
                Total recibido
              </span>
              <span className="font-display text-xl">
                S/{" "}
                {order.items
                  .reduce(
                    (sum, item) =>
                      sum + item.receivedQuantity * (item.unitCost ?? 0),
                    0,
                  )
                  .toFixed(2)}
              </span>
            </div>
          )}
          {order.notes && (
            <p className="mt-5 whitespace-pre-wrap text-sm text-muted-foreground">
              {order.notes}
            </p>
          )}
        </Card>

        <div className="space-y-6">
          <Card className="space-y-3 rounded-[30px] bg-white/85 p-6 text-sm">
            <div className="flex justify-between">
              <span className="text-foreground/50">Estado</span>
              <OrderStatusBadge status={order.status} />
            </div>
            <div className="flex justify-between">
              <span className="text-foreground/50">Creada</span>
              <span>
                {new Date(order.createdAt).toLocaleDateString("es-PE")}
              </span>
            </div>
            {order.receivedAt && (
              <div className="flex justify-between">
                <span className="text-foreground/50">Recibida</span>
                <span>
                  {new Date(order.receivedAt).toLocaleDateString("es-PE")}
                </span>
              </div>
            )}
            {order.stockEntryId && (
              <div className="space-y-2 border-t pt-3">
                <p className="text-muted-foreground">Entrada vinculada</p>
                <p className="break-all font-mono text-xs">
                  {order.stockEntryId}
                </p>
                <Link
                  href="/inventory/entries"
                  className="inline-block font-medium underline"
                >
                  Ver entradas de inventario
                </Link>
              </div>
            )}
          </Card>

          <OrderActions order={order} />
        </div>
      </div>
    </div>
  );
}
