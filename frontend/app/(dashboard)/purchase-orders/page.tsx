import Link from "next/link";
import { Card } from "@/components/ui/card";
import { serverApiFetch } from "@/lib/server-api";
import { getServerSession } from "@/lib/session";
import { AutoOrdersPanel } from "@/components/suppliers/auto-orders-panel";
import { OrderStatusBadge } from "@/components/suppliers/order-status-badge";
import type { AutoOrdersPreview, SupplierOrder } from "@/types/suppliers";
import { ClipboardList, Sparkles, Plus } from "lucide-react";
import { PermissionGuard } from "@/components/auth/permission-guard";
import { Button } from "@/components/ui/button";
import { getCompanySettings } from "@/lib/company-settings-server";
import { companyDateLabel, validCompanyZone } from "@/lib/company-format";

export default async function PurchaseOrdersPage() {
  const session = await getServerSession();
  const accessToken = session?.accessToken;
  const companySettings = await getCompanySettings(accessToken);
  const zone = validCompanyZone(companySettings?.timezone);

  const [orders, preview] = await Promise.all([
    serverApiFetch<SupplierOrder[]>("/suppliers/orders", accessToken),
    serverApiFetch<AutoOrdersPreview>(
      "/suppliers/auto-orders/preview",
      accessToken,
    ),
  ]);

  const orderList = Array.isArray(orders) ? orders : [];

  return (
    <div className="space-y-6">
      <Card className="rounded-[34px] bg-gradient-to-br from-slate-700 to-slate-900 p-6 sm:p-8 text-white animate-fade-in-up">
        <div className="flex flex-wrap items-center gap-4">
          <div className="rounded-2xl bg-white/20 p-3">
            <ClipboardList className="size-6" />
          </div>
          <div className="min-w-0 flex-1">
            <h1 className="font-display text-3xl sm:text-4xl">
              Órdenes de compra
            </h1>
            <p className="mt-1 text-sm text-white/70">
              {orderList.length} órdenes en esta vista · hasta 200 recientes
            </p>
          </div>
          <PermissionGuard permission="supplier_order:manage">
            <Button
              asChild
              className="rounded-xl bg-white text-slate-900 hover:bg-white/90"
            >
              <Link href="/purchase-orders/new">
                <Plus className="size-4" />
                Nueva orden de compra
              </Link>
            </Button>
          </PermissionGuard>
        </div>
      </Card>

      <AutoOrdersPanel preview={preview ?? { groups: [], unassigned: [] }} />

      <Card className="rounded-[34px] bg-white/85 p-6 animate-fade-in-up delay-200">
        <p className="mb-4 flex items-center gap-2 font-display text-lg">
          <Sparkles className="size-5 text-orange-600" />
          Órdenes recientes
        </p>
        {orderList.length > 0 ? (
          <div className="divide-y divide-foreground/10">
            {orderList.map((order) => (
              <Link
                key={order.id}
                href={`/purchase-orders/${order.id}`}
                className="flex items-center justify-between gap-4 py-4 transition hover:bg-foreground/5 sm:px-3"
              >
                <div className="min-w-0">
                  <p className="truncate font-medium">
                    {order.supplier?.name ?? "Proveedor"}
                    {order.isAutoGenerated && (
                      <span className="ml-2 rounded-full bg-orange-500/15 px-2 py-0.5 text-xs font-medium text-orange-600">
                        Auto
                      </span>
                    )}
                  </p>
                  <p className="mt-1 text-xs text-foreground/50">
                    {order.items.length} productos ·{" "}
                    {companyDateLabel(order.createdAt, zone)}
                  </p>
                </div>
                <div className="flex shrink-0 items-center gap-3">
                  {order.totalEstimated !== null && (
                    <span className="text-sm font-medium">
                      S/ {order.totalEstimated.toFixed(2)}
                    </span>
                  )}
                  <OrderStatusBadge status={order.status} />
                </div>
              </Link>
            ))}
          </div>
        ) : (
          <div className="py-10 text-center text-foreground/50">
            Aún no hay órdenes de compra.
          </div>
        )}
      </Card>
    </div>
  );
}
