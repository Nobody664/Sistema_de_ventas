function handle(resource, params, method, body) {
  if (resource === "/notifications/preferences")
    return { salesEnabled: true, stockEnabled: true, soundEnabled: false };
  if (resource === "/companies/current")
    return {
      id: user.companyId,
      name: "Negocio de prueba",
      legalName: null,
      taxId: null,
      address: null,
      email: null,
      phone: null,
      timezone: "America/Lima",
      currency: "PEN",
    };
  if (resource === "/auth/me") return { ...user, roles };
  if (resource === "/notifications/unread-count") return { count: 0 };
  if (resource === "/plan-capabilities/me")
    return {
      planId: "plan",
      planCode: "START",
      planName: "Start",
      modules: [
        "products",
        "categories",
        "inventory",
        "sales",
        "dashboard",
        "notifications",
        "reports",
      ],
      features: [],
      apiEnabled: false,
      maxUsers: 10,
      maxProducts: 1000,
    };
  if (resource === "/products/categories")
    return [
      { id: "category-a", name: "Galletas", _count: { products: 50 } },
      { id: "category-b", name: "Insumos", _count: { products: 10 } },
      { id: "category-empty", name: "Sin productos", _count: { products: 0 } },
    ];
  if (resource === "/products/catalog") {
    const page = Number(params.get("page") || 1);
    const limit = Number(params.get("limit") || 50);
    const search = (params.get("search") || "").toLowerCase();
    const category = params.get("categoryId");
    const filtered = products.filter(
      (product) =>
        (!category || product.categoryId === category) &&
        (!search ||
          [product.name, product.sku, product.barcode].some((value) =>
            value.toLowerCase().includes(search),
          )),
    );
    return {
      data: filtered.slice((page - 1) * limit, page * limit),
      total: filtered.length,
      page,
      limit,
      totalPages: Math.ceil(filtered.length / limit),
    };
  }
  if (resource === "/suppliers") return [supplier];
  if (resource === "/suppliers/auto-orders/preview")
    return { groups: [], unassigned: [] };
  if (resource === "/suppliers/orders" && method === "GET")
    return [...orders.values()].reverse();
  if (resource === "/suppliers/orders" && method === "POST") {
    assert.equal(body.supplierId, supplier.id);
    assert.equal("companyId" in body, false);
    assert.equal(
      new Set(body.items.map((item) => item.productId)).size,
      body.items.length,
    );
    createdPayloads.push(body);
    const id = `order-${orders.size + 1}`;
    const items = body.items.map((item, index) => ({
      ...item,
      id: `${id}-item-${index}`,
      orderId: id,
      suggestedQuantity: item.requestedQuantity,
      receivedQuantity: 0,
      unitCost: item.unitCost ?? null,
      product: products.find((product) => product.id === item.productId),
    }));
    const order = {
      id,
      companyId: user.companyId,
      supplierId: supplier.id,
      supplier,
      status: "DRAFT",
      reference: body.reference ?? null,
      notes: body.notes ?? null,
      items,
      totalEstimated: items.every((item) => item.unitCost !== null)
        ? items.reduce(
            (sum, item) => sum + item.unitCost * item.requestedQuantity,
            0,
          )
        : null,
      isAutoGenerated: false,
      stockEntryId: null,
      receivedAt: null,
      createdAt: new Date().toISOString(),
    };
    orders.set(id, order);
    return order;
  }
  const match = resource.match(
    /^\/suppliers\/orders\/(order-\d+)(?:\/(status|receive))?$/,
  );
  if (match) {
    const order = orders.get(match[1]);
    assert.ok(order);
    if (method === "PATCH" && match[2] === "status") {
      assert.ok(["DRAFT", "SENT"].includes(order.status));
      assert.ok(["SENT", "CANCELLED"].includes(body.status));
      order.status = body.status;
    }
    if (method === "POST" && match[2] === "receive") {
      if (order.receivedAt) return { ...order, alreadyReceived: true };
      assert.notEqual(order.status, "CANCELLED");
      assert.equal(body.items.length, order.items.length);
      for (const item of body.items) {
        const line = order.items.find(
          (value) => value.productId === item.productId,
        );
        assert.equal(item.quantity, line.requestedQuantity);
        assert.equal(typeof item.unitCost, "number");
        assert.ok(Number.isFinite(item.unitCost));
        const product = products.find((value) => value.id === item.productId);
        product.stockQuantity = String(
          Number(product.stockQuantity) + item.quantity,
        );
        line.receivedQuantity = item.quantity;
        line.unitCost = item.unitCost;
      }
      stockWrites++;
      order.status = "CONFIRMED";
      order.receivedAt = new Date().toISOString();
      order.stockEntryId = `entry-${order.id}`;
    }
    return order;
  }
  return [];
}

const backend = http.createServer(async (request, response) => {
  try {
    const url = new URL(request.url, apiOrigin);
    const resource = url.pathname.replace(/^\/api/, "");
    response.setHeader("Content-Type", "application/json");
    if (
      !["GET", "HEAD", "OPTIONS"].includes(request.method) &&
      !(request.headers["content-type"] || "").startsWith("application/json")
    ) {
      response.statusCode = 403;
      return response.end(JSON.stringify({ message: "CSRF requiere JSON" }));
    }
    const chunks = [];
    for await (const chunk of request) chunks.push(chunk);
    const text = Buffer.concat(chunks).toString();
    response.end(
      JSON.stringify(
        handle(
          resource,
          url.searchParams,
          request.method,
          text ? JSON.parse(text) : {},
        ),
      ),
    );
  } catch (error) {
    response.statusCode = 400;
    response.end(JSON.stringify({ message: error.message }));
  }
});

